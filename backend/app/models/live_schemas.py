"""
live_schemas.py — Pydantic Schemas for Live Meeting Sessions & AI Insights.

Defines the structure for:
- Live session states and updates (Google Meet live capture)
- Live transcript chunks and speaker attribution
- Incremental structured AI insights (summary, key points, decisions, action items, questions, topics, risks)
- Real-time WebSocket messages streamed to the frontend
"""

from typing import Optional, List, Dict, Any
from datetime import datetime
from pydantic import BaseModel, Field


# ============================================================
# Live AI Insights Schemas
# ============================================================

class LiveActionItem(BaseModel):
    """An action item detected during a live meeting."""
    task: str
    owner: Optional[str] = "Not specified"
    deadline: Optional[str] = "No deadline specified"
    priority: Optional[str] = "Not specified"


class LiveInsightsData(BaseModel):
    """
    Incremental structured intelligence generated by Gemini during live sessions.
    Constrained by JSON schema for predictable updates.
    """
    summary: str = ""
    key_points: List[str] = Field(default_factory=list)
    decisions: List[str] = Field(default_factory=list)
    action_items: List[LiveActionItem] = Field(default_factory=list)
    open_questions: List[str] = Field(default_factory=list)
    topics: List[str] = Field(default_factory=list)
    risks: List[str] = Field(default_factory=list)


# ============================================================
# Live Transcript Schemas
# ============================================================

class LiveTranscriptChunk(BaseModel):
    """A normalized live transcript chunk received from speech-to-text."""
    speaker_id: Optional[str] = None
    speaker_name: str = "Speaker"
    start_time: Optional[str] = None
    end_time: Optional[str] = None
    text: str
    language: Optional[str] = "en"
    sequence_number: Optional[int] = 0
    chunk_hash: Optional[str] = None
    created_at: Optional[str] = None


# ============================================================
# Live Meeting Session Schemas
# ============================================================

class LiveMeetingSessionResponse(BaseModel):
    """Public representation of a live meeting session."""
    id: str
    user_id: str
    title: str = "Google Meet — Live Session"
    source: str = "google_meet"
    status: str = "waiting"  # waiting | live | processing | completed | disconnected | failed
    started_at: Optional[str] = None
    ended_at: Optional[str] = None
    last_transcript_at: Optional[str] = None
    current_summary: Optional[str] = None
    current_insights: Optional[Dict[str, Any]] = None
    final_meeting_id: Optional[str] = None
    error_message: Optional[str] = None
    created_at: Optional[str] = None
    updated_at: Optional[str] = None


class LiveSessionStatus(BaseModel):
    """Quick status check for active live sessions."""
    is_active: bool
    session: Optional[LiveMeetingSessionResponse] = None


# ============================================================
# Real-Time WebSocket Message Schemas
# ============================================================

class WebSocketEvent(BaseModel):
    """Standardized event packet broadcast over WebSocket to frontend."""
    type: str  # 'status' | 'transcript' | 'insights' | 'meeting_ended' | 'error'
    session_id: str
    data: Dict[str, Any]
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
